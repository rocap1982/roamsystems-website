"""Clean seat side-view for the website: one filled silhouette (outline + see-through openings)
and the cushion cross-section at the seat centreline. Output in mm: x from ski heel (front negative),
y above the floor under the skis (y up)."""
import sys, json, math
sys.path.insert(0, sys.argv[1])
from cad_lib import *
from OCP.TopAbs import TopAbs_SOLID, TopAbs_SHELL, TopAbs_FACE, TopAbs_EDGE
from OCP.BRepMesh import BRepMesh_IncrementalMesh
from OCP.BRep import BRep_Tool
from OCP.TopLoc import TopLoc_Location
from OCP.TopoDS import TopoDS
from OCP.TopExp import TopExp_Explorer
from OCP.BRepAlgoAPI import BRepAlgoAPI_Section
from OCP.BRepBuilderAPI import BRepBuilderAPI_MakeFace
from OCP.gp import gp_Pln, gp_Pnt, gp_Dir
from OCP.BRepAdaptor import BRepAdaptor_Curve
from OCP.GCPnts import GCPnts_QuasiUniformDeflection
from shapely.geometry import Polygon, MultiPolygon
from shapely.ops import unary_union
P = lambda z, y: (-(z + 91.0), y + 485.0)
SEAT = ['p0002','p0003','p0005','p0006','p0007','p0008','p0009','p0010','p0011','p0012','p0013','p0014','p0022','p0023','p0024']
tris = []
for f in SEAT:
    s = load(f + '.brep')
    parts = [sh for sh in sub(s, TopAbs_SHELL) if bb(sh)[1] < 800] if f == 'p0003' else [s]
    for shape in parts:
        BRepMesh_IncrementalMesh(shape, 0.6, False, 0.4, True)
        ex = TopExp_Explorer(shape, TopAbs_FACE)
        while ex.More():
            fc = TopoDS.Face_s(ex.Current()); ex.Next()
            loc = TopLoc_Location(); tr = BRep_Tool.Triangulation_s(fc, loc)
            if tr is None: continue
            T = loc.Transformation()
            pts = [tr.Node(i).Transformed(T) for i in range(1, tr.NbNodes() + 1)]
            for k in range(1, tr.NbTriangles() + 1):
                a, b, c = tr.Triangle(k).Get()
                poly = Polygon([P(pts[a-1].Z(), pts[a-1].Y()), P(pts[b-1].Z(), pts[b-1].Y()), P(pts[c-1].Z(), pts[c-1].Y())])
                if poly.area > 1e-3: tris.append(poly)
print('triangles', len(tris), flush=True)
sil = unary_union([t.buffer(0.15, join_style=2) for t in tris]).buffer(-0.15, join_style=2)
sil = sil.simplify(0.8, preserve_topology=True)
geoms = list(sil.geoms) if isinstance(sil, MultiPolygon) else [sil]
geoms = [g for g in geoms if g.area > 50]
def ring(c): return 'M' + ' L'.join('%.1f %.1f' % (x, y) for x, y in list(c.coords)[:-1]) + ' Z'
d = []
holes = 0
for g in geoms:
    d.append(ring(g.exterior))
    for h in g.interiors:
        if Polygon(h).area > 300: d.append(ring(h)); holes += 1
print('silhouette parts', len(geoms), 'openings', holes, 'bounds', [round(v) for v in unary_union(geoms).bounds])
# cushion section at the seat centreline (model x = -378)
cush = sub(load('p0061.brep'), TopAbs_SOLID)
face = BRepBuilderAPI_MakeFace(gp_Pln(gp_Pnt(-378, 0, 0), gp_Dir(1, 0, 0)), -3000, 3000, -3000, 3000).Face()
cpaths = []
for i in (4, 5, 6):
    segs = []
    ex = TopExp_Explorer(BRepAlgoAPI_Section(cush[i], face).Shape(), TopAbs_EDGE)
    while ex.More():
        e = TopoDS.Edge_s(ex.Current()); ex.Next()
        c = BRepAdaptor_Curve(e); q = GCPnts_QuasiUniformDeflection(c, 0.3)
        segs.append([P(q.Value(k).Z(), q.Value(k).Y()) for k in range(1, q.NbPoints() + 1)])
    loop = segs.pop(0)
    while segs:
        end = loop[-1]
        j = min(range(len(segs)), key=lambda j: min(math.dist(end, segs[j][0]), math.dist(end, segs[j][-1])))
        s = segs.pop(j)
        if math.dist(end, s[-1]) < math.dist(end, s[0]): s = s[::-1]
        loop += s[1:]
    cpaths.append(ring(Polygon(loop).buffer(0).simplify(0.6).exterior))
out = {'units': 'mm; x from ski heel (front negative), y above floor (up)', 'frame': ' '.join(d), 'cushions': cpaths,
       'r_point': [-427, 515], 'note': 'generated by hc_seatclean.py from the owner SolidWorks export; rear travel seat only, head rest concept excluded'}
json.dump(out, open(sys.argv[2], 'w'))
print('frame chars', len(out['frame']), 'cushion chars', [len(c) for c in cpaths])
